//! Email Alert Channel
//!
//! Send alerts via SMTP.
//!
//! ## Configuration
//!
//! ```yaml
//! channels:
//!   email:
//!     type: email
//!     smtp_host: "smtp.gmail.com"
//!     smtp_port: 587
//!     username: "${EMAIL_USER}"
//!     password: "${EMAIL_PASS}"
//!     use_tls: true
//!     from: "alerts@fluxx.dev"
//!     to:
//!       - "ops@company.com"
//!       - "oncall@company.com"
//! ```

use super::{AlertChannel, ChannelError, ChannelResult, ChannelType};
