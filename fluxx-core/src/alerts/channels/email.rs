#[async_trait]
impl AlertChannel for EmailChannel {
    fn name(&self) -> &str {
        &self.name
    }

    async fn send(&self, alert: &Alert) -> ChannelResult<()> {
        let subject = self.build_subject(alert);
        let html_body = self.build_html_body(alert);
        let text_body = self.build_text_body(alert);

        self.send_email(&subject, &html_body, &text_body).await
    }

    async fn health_check(&self) -> ChannelResult<()> {
        // Try to connect to SMTP server
        // For now, just validate configuration
        if self.smtp_host.is_empty() {
            return Err(ChannelError::Config("SMTP host is empty".to_string()));
        }
        if self.to.is_empty() {
            return Err(ChannelError::Config("No recipients configured".to_string()));
        }

        tracing::info!(
            channel = %self.name,
            smtp_host = %self.smtp_host,
            "Email channel configuration looks valid"
        );

        Ok(())
    }

    fn channel_type(&self) -> ChannelType {
        ChannelType::Email
    }
}

/// Escape HTML special characters
fn html_escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&#x27;")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn create_test_alert() -> Alert {
        Alert {
            id: "test-123".to_string(),
            severity: AlertSeverity::Critical,
            message: "Test alert with <special> & characters".to_string(),
            source: "test_source".to_string(),
            timestamp_us: 1704067200000000,
        }
    }

    fn create_test_config() -> ChannelConfig {
        ChannelConfig::Email {
            smtp_host: "smtp.gmail.com".to_string(),
            smtp_port: 587,
            username: "test@gmail.com".to_string(),
            password: "password".to_string(),
            use_tls: true,
            from: "alerts@fluxx.dev".to_string(),
            to: vec!["ops@company.com".to_string()],
            cc: vec![],
        }
    }

    #[test]
    fn test_build_subject() {
        let config = create_test_config();
        let channel = EmailChannel::new("email", &config).unwrap();
        let alert = create_test_alert();
        let subject = channel.build_subject(&alert);

        assert!(subject.contains("CRITICAL"));
        assert!(subject.contains("Fluxx Agent Alert"));
    }

    #[test]
    fn test_html_escape() {
        assert_eq!(html_escape("<script>"), "&lt;script&gt;");
        assert_eq!(html_escape("&"), "&amp;");
        assert_eq!(html_escape("\"test\""), "&quot;test&quot;");
    }

    #[test]
    fn test_html_body_contains_fields() {
        let config = create_test_config();
        let channel = EmailChannel::new("email", &config).unwrap();
        let alert = create_test_alert();
        let body = channel.build_html_body(&alert);

        assert!(body.contains(&alert.id));
        assert!(body.contains("CRITICAL"));  // severity in uppercase
        assert!(body.contains(&alert.source));
    }
}
