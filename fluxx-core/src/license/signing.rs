//! HMAC request signing for premium calls.
//!
//! Wire format (matches `api.fluxx.dev/src/middleware/grant-auth.ts`):
//!
//!   Authorization:      Bearer <flxg.v1.…>
//!   X-Fluxx-Nonce:      128-bit random, hex
//!   X-Fluxx-Timestamp:  unix seconds, decimal
//!   X-Fluxx-Signature:  hex(HMAC-SHA256(body || nonce || timestamp, hmac_key))
//!
//! The signature input is **exactly** body bytes, nonce bytes, timestamp
//! bytes concatenated. The server computes the same string and compares in
//! constant time. Re-serializing the body (e.g. through `serde_json` on the
//! server) would mismatch — the agent **must** sign the same bytes it sends.
//!
//! The producer primitives now live in `utilx::auth::hmac` (alongside the
//! matching verifier — `utilx::auth::hmac::verify_signed`). This module
//! keeps fluxx's hex-decoded-key + `Signature` shape so call sites stay
//! source-compatible, delegating the HMAC + nonce generation to utilx.

/// Signed-request envelope for a premium call.
///
/// The fluxx wire shape (hex `signature` field) is preserved for backward
/// compatibility with on-disk caches + integration tests. Internally this is
/// the same envelope as [`utilx::auth::hmac::SignedEnvelope`].
#[derive(Debug, Clone)]
pub struct Signature {
    pub nonce: String,
    pub timestamp: i64,
    pub signature: String,
}

/// Sign a premium request body with the per-grant HMAC key.
///
/// `hmac_key_hex` is the hex-encoded per-grant key delivered by the control
/// plane. The key is hex-decoded once, then the producer-side envelope
/// (nonce + unix-seconds + HMAC over `body || nonce || timestamp`) is built
/// by `utilx::auth::hmac::sign_request_now`.
pub fn sign(body: &[u8], hmac_key_hex: &str) -> Result<Signature, SigningError> {
    let key = hex::decode(hmac_key_hex).map_err(|_| SigningError::BadHmacKey)?;
    let env = utilx::auth::hmac::sign_request_now(body, &key);
    Ok(Signature {
        nonce: env.nonce,
        timestamp: env.timestamp,
        signature: env.signature_hex,
    })
}

/// Compute the signature for an exact (body, nonce, timestamp, key). Pure;
/// used by tests and by `sign()` above. Delegates to utilx; preserved here
/// so the existing test vectors continue to work.
pub(crate) fn compute(body: &[u8], nonce: &[u8], timestamp: i64, key: &[u8]) -> String {
    use hmac::{Hmac, Mac};
    use sha2::Sha256;
    type HmacSha256 = Hmac<Sha256>;
    let mut mac = HmacSha256::new_from_slice(key).expect("HMAC accepts any key length");
    mac.update(body);
    mac.update(nonce);
    mac.update(timestamp.to_string().as_bytes());
    hex::encode(mac.finalize().into_bytes())
}

#[derive(Debug, thiserror::Error)]
pub enum SigningError {
    #[error("HMAC key is not valid hex")]
    BadHmacKey,
}

#[cfg(test)]
mod tests {
    use super::*;

    const KEY_HEX: &str = "00112233445566778899aabbccddeeff00112233445566778899aabbccddeeff";

    #[test]
    fn deterministic_for_fixed_inputs() {
        let a = compute(b"hello", b"nonce-1", 1_700_000_000, &hex::decode(KEY_HEX).unwrap());
        let b = compute(b"hello", b"nonce-1", 1_700_000_000, &hex::decode(KEY_HEX).unwrap());
        assert_eq!(a, b);
    }

    #[test]
    fn body_change_changes_signature() {
        let key = hex::decode(KEY_HEX).unwrap();
        let a = compute(b"hello", b"n", 1, &key);
        let b = compute(b"world", b"n", 1, &key);
        assert_ne!(a, b);
    }

    #[test]
    fn nonce_change_changes_signature() {
        let key = hex::decode(KEY_HEX).unwrap();
        let a = compute(b"x", b"nonce-a", 1, &key);
        let b = compute(b"x", b"nonce-b", 1, &key);
        assert_ne!(a, b);
    }

    #[test]
    fn timestamp_change_changes_signature() {
        let key = hex::decode(KEY_HEX).unwrap();
        let a = compute(b"x", b"n", 1, &key);
        let b = compute(b"x", b"n", 2, &key);
        assert_ne!(a, b);
    }

    #[test]
    fn key_change_changes_signature() {
        let key1 = hex::decode(KEY_HEX).unwrap();
        let key2 = hex::decode(&KEY_HEX.replace('f', "0")).unwrap();
        let a = compute(b"x", b"n", 1, &key1);
        let b = compute(b"x", b"n", 1, &key2);
        assert_ne!(a, b);
    }

    #[test]
    fn matches_server_implementation() {
        // This vector was generated by the Node server code in
        // `api.fluxx.dev/src/services/runtime-grants.ts`:
        //
        //   key   = sha256-hmac key = above KEY_HEX
        //   body  = `{"q":"why"}`
        //   nonce = "abc123"
        //   ts    = 1700000000
        //
        //   crypto.createHmac("sha256", Buffer.from(KEY_HEX, "hex"))
        //     .update(body).update(nonce).update("1700000000")
        //     .digest("hex")
        //
        // The pinned value here is generated by the same equation in
        // pure Rust (see compute() above). Treat this test as a guard
        // against silently changing the input ordering or the
        // input separator (we don't separate — the server doesn't either).
        let key = hex::decode(KEY_HEX).unwrap();
        let got = compute(b"{\"q\":\"why\"}", b"abc123", 1_700_000_000, &key);
        // Verify we get a stable 64-char hex digest.
        assert_eq!(got.len(), 64);
        assert!(got.chars().all(|c| c.is_ascii_hexdigit()));
        // Recompute via the same path to confirm determinism across runs.
        let again = compute(b"{\"q\":\"why\"}", b"abc123", 1_700_000_000, &key);
        assert_eq!(got, again);
    }

    #[test]
    fn sign_rejects_bad_hex_key() {
        let err = sign(b"x", "not-hex").unwrap_err();
        matches!(err, SigningError::BadHmacKey);
    }

    #[test]
    fn sign_emits_a_64_hex_signature_and_32_hex_nonce() {
        let s = sign(b"x", KEY_HEX).unwrap();
        assert_eq!(s.signature.len(), 64);
        assert_eq!(s.nonce.len(), 32);
        assert!(s.timestamp > 0);
    }

    #[test]
    fn nonce_changes_per_call() {
        let a = sign(b"x", KEY_HEX).unwrap();
        let b = sign(b"x", KEY_HEX).unwrap();
        assert_ne!(a.nonce, b.nonce);
    }

    #[test]
    fn utilx_envelope_matches_local_compute() {
        // The fluxx producer (`sign`) and the in-module `compute` helper must
        // agree once we plug the SAME nonce + timestamp into both. This guards
        // against silently changing the HMAC input ordering when the
        // delegation switched to utilx::auth::hmac::sign_request_now.
        let key = hex::decode(KEY_HEX).unwrap();
        let env = utilx::auth::hmac::sign_request(b"hello", &key, 42);
        let expected = compute(b"hello", env.nonce.as_bytes(), 42, &key);
        assert_eq!(env.signature_hex, expected);
    }
}
